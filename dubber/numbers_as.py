HUNDREDS = {1: "এশ", 2: "দুশ", 3: "তিনিশ", 4: "চাৰিশ", 5: "পাঁচশ", 6: "ছশ",
            7: "সাতশ", 8: "আঠশ", 9: "নশ"}
AS_DIGITS = str.maketrans("০১২৩৪৫৬৭৮৯", "0123456789")


def to_words(n: int) -> str:
    if n < 100:
        return ONES[n]
    parts = []
    for value, word in ((10**7, "কোটি"), (10**5, "লাখ"), (1000, "হাজাৰ")):
        if n >= value:
            parts.append(f"{to_words(n // value)} {word}")
            n %= value
    if n >= 100:
        parts.append(HUNDREDS[n // 100])
        n %= 100
    if n:
        parts.append(ONES[n])
    return " ".join(parts)


_NUM = re.compile(r"[0-9০-৯][0-9০-৯,]*(?:\.[0-9০-৯]+)?")


def numbers_to_words(text: str) -> str:
    def repl(m):
        raw = m.group(0).translate(AS_DIGITS).rstrip(",")
        tail = m.group(0)[len(raw):]
        if "." in raw:                              # 2.5 -> দুই দশমিক পাঁচ
            whole, frac = raw.split(".", 1)
            return (to_words(int(whole.replace(",", "") or 0)) + " দশমিক " +
                    " ".join(ONES[int(d)] for d in frac)) + tail
        digits = raw.replace(",", "")
        if not digits or len(digits) > 12:
            return m.group(0)
        return to_words(int(digits)) + tail
    return _NUM.sub(repl, text)
